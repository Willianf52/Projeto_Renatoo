-- ============================================================================
-- 0095: numero sequencial de cada conta (coluna ID da tela de Usuarios)
--
-- POR QUE EXISTE (06/11/2026): na comparacao com o sistema antigo, o dono pediu
-- a coluna ID da lista de Usuarios. O id de `profiles` e um UUID, longo demais
-- para uma coluna de lista; o antigo mostra um numero. Este numero e NOVO: nao
-- e o do sistema antigo.
--
-- As contas que ja existem sao numeradas pela ordem de criacao; as novas pegam
-- o proximo numero sozinhas (identity). Ninguem altera o numero pelo painel: o
-- `authenticated` so tem UPDATE em `nome_completo` (0002/0007), e a leitura e
-- da tabela inteira, entao a coluna nova ja sai no select.
-- ============================================================================

alter table public.profiles add column if not exists numero bigint;

with ordem as (
  select id, row_number() over (order by created_at, id) as n
    from public.profiles
)
update public.profiles p
   set numero = o.n
  from ordem o
 where o.id = p.id
   and p.numero is null;

alter table public.profiles alter column numero set not null;
alter table public.profiles alter column numero add generated by default as identity;

-- O identity nasce em 1: passa a continuar depois do maior numero ja dado.
select setval(
  pg_get_serial_sequence('public.profiles', 'numero'),
  (select coalesce(max(numero), 0) + 1 from public.profiles),
  false
);

alter table public.profiles
  add constraint profiles_numero_key unique (numero);

comment on column public.profiles.numero is
  'Numero sequencial da conta, exibido como ID na lista de Usuarios (0095). Nao e o ID do sistema antigo.';
